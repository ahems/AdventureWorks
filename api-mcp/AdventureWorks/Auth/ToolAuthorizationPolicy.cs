    private static readonly IReadOnlyDictionary<string, ToolPolicy> ByName =
        Policies.ToDictionary(p => p.Tool, StringComparer.Ordinal);

    /// <summary>All registered policies.</summary>
    public static IReadOnlyCollection<ToolPolicy> All => Policies;

    /// <summary>All tool names that have a policy.</summary>
    public static IReadOnlyCollection<string> ToolNames => ByName.Keys.ToArray();

    /// <summary>Looks up the policy for a tool, or null if unclassified.</summary>
    public static ToolPolicy? Find(string toolName) =>
        toolName is not null && ByName.TryGetValue(toolName, out var p) ? p : null;
