namespace AdventureWorks.Auth;

/// <summary>
/// How a tool is authorized beyond the required scope.
/// </summary>
public enum ToolAccessMode
{
    /// <summary>Any caller holding <see cref="ToolPolicy.RequiredScope"/> may call the tool.</summary>
    Public,

    /// <summary>
    /// The tool exposes per-customer data. Consumers may only access their own records
    /// (the <see cref="ToolPolicy.OwnerArgument"/> is validated / injected against the
    /// caller's resolved CustomerID). Internal roles holding the scope are unrestricted.
    /// </summary>
    SelfOrInternal,

    /// <summary>
    /// Internal-only tool. Requires the scope AND a non-consumer category. Consumers are
    /// denied even if a token somehow carries the scope (defense in depth).
    /// </summary>
    InternalOnly,
}

/// <summary>Authorization policy for a single MCP tool.</summary>
/// <param name="Tool">The MCP wire name (snake_case) as generated by the SDK.</param>
/// <param name="RequiredScope">The single business-domain scope required to invoke the tool.</param>
/// <param name="Mode">Access mode (scope-only, ownership, or internal-only).</param>
/// <param name="OwnerArgument">
/// For <see cref="ToolAccessMode.SelfOrInternal"/>, the tool argument (camelCase) that carries the
/// customer identifier subject to ownership enforcement. Null for other modes.
/// </param>
public sealed record ToolPolicy(string Tool, string RequiredScope, ToolAccessMode Mode, string? OwnerArgument = null);

